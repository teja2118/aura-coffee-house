function startAuraMusic(showMessage = false) {
    if (!cozyAudio || userTurnedSoundOff) return;
    // Keep the background music quiet and only start it after the visitor presses Sound.
    cozyAudio.volume = 0.18;
    cozyAudio.currentTime = 0;
    cozyAudio.play().then(() => {
        updateSoundButton(true);
        if (showMessage && typeof showToast === "function") {
            showToast(currentLanguage === "mk" ? "Музиката е вклучена ♪" : "Music is on ♪");
        }
    }).catch(() => {
        updateSoundButton(false);
        if (typeof showToast === "function") {
            showToast(currentLanguage === "mk"
                ? "Не може да се пушти музиката. Провери дали аудио-датотеката е во папката audio."
                : "Music could not play. Check that the audio file is inside the audio folder.");
        }
    });
}

if (soundToggle && cozyAudio) {
    soundToggle.addEventListener("click", () => {
        if (isPlayingSound) {
            userTurnedSoundOff = true;
            cozyAudio.pause();
            cozyAudio.currentTime = 0;
            updateSoundButton(false);
            if (typeof showToast === "function") showToast(currentLanguage === "mk" ? "Музиката е исклучена." : "Music is off.");
        } else {
            userTurnedSoundOff = false;
            startAuraMusic(true);
        }
    });
    // Do not autoplay: the visitor starts the music deliberately with the Sound button.
    cozyAudio.addEventListener("ended", () => updateSoundButton(false));
    cozyAudio.addEventListener("error", () => updateSoundButton(false));
}

